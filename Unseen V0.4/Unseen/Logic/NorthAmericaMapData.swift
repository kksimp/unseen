// MARK: - Coordinate Conversion

struct MapCoordinates {
    // North America bounds (longitude, latitude)
    static let minLon: Float = -170
    static let maxLon: Float = -50
    static let minLat: Float = 14
    static let maxLat: Float = 72
    
    // Map size in SceneKit units
    static let mapWidth: Float = 50
    static let mapHeight: Float = 30
    
    // Convert longitude/latitude to SceneKit X/Z coordinates
    static func toSceneKit(lon: Float, lat: Float) -> CGPoint {
        let x = ((lon - minLon) / (maxLon - minLon)) * mapWidth - (mapWidth / 2)
        let z = ((maxLat - lat) / (maxLat - minLat)) * mapHeight - (mapHeight / 2)
        return CGPoint(x: CGFloat(x), y: CGFloat(z))
    }
}

